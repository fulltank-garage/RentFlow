		protected.PATCH("/partner/cars/:carId/images/reorder", controllers.RentFlowCarPartnerReorderCarImages)
		protected.DELETE("/partner/cars/:carId/images/:imageId", controllers.RentFlowCarPartnerDeleteCarImage)
