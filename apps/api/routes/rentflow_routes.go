	r.GET("/cars/:carId/images/:imageId", controllers.RentFlowCarGetCarImage)
	r.GET("/branches", controllers.RentFlowCarGetBranches)
	r.GET("/branches/:branchId", controllers.RentFlowCarGetBranchByID)
