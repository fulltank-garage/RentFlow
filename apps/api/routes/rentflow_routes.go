	r.POST("/auth/login", controllers.RentFlowCarLogin)
	r.POST("/auth/forgot-password", controllers.RentFlowCarForgotPassword)
	r.GET("/auth/me", controllers.RentFlowCarGetMe)
	r.POST("/auth/logout", controllers.RentFlowCarLogout)
	r.POST("/platform/auth/login", controllers.RentFlowCarAdminLogin)
	r.GET("/tenants", controllers.RentFlowCarListPublicTenants)
