		protected.PATCH("/users/me", controllers.RentFlowCarUpdateMe)
		protected.PATCH("/users/me/password", controllers.RentFlowCarChangePassword)

		protected.GET("/tenants/me", controllers.RentFlowCarGetMyTenant)
		protected.POST("/tenants/me", controllers.RentFlowCarUpsertMyTenant)
		protected.PUT("/tenants/me", controllers.RentFlowCarUpsertMyTenant)

