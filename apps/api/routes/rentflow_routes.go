		protected.POST("/partner/branches", controllers.RentFlowCarPartnerCreateBranch)
		protected.PATCH("/partner/branches/:branchId", controllers.RentFlowCarPartnerUpdateBranch)
		protected.DELETE("/partner/branches/:branchId", controllers.RentFlowCarPartnerDeleteBranch)
		protected.GET("/partner/bookings", controllers.RentFlowCarPartnerGetBookings)
		protected.PATCH("/partner/bookings/:bookingId/status", controllers.RentFlowCarPartnerUpdateBookingStatus)
		protected.GET("/partner/bookings/:bookingId/operations", controllers.RentFlowCarPartnerGetBookingOperations)
		protected.POST("/partner/bookings/:bookingId/operations", controllers.RentFlowCarPartnerCreateBookingOperation)
		protected.GET("/partner/payments", controllers.RentFlowCarPartnerGetPayments)
		protected.PATCH("/partner/payments/:paymentId/verify", controllers.RentFlowCarPartnerVerifyPayment)
		protected.PATCH("/partner/payments/:paymentId/refund", controllers.RentFlowCarPartnerRefundPayment)
		protected.PATCH("/partner/payments/:paymentId/settle", controllers.RentFlowCarPartnerSettlePayment)
		protected.GET("/partner/customers", controllers.RentFlowCarPartnerGetCustomers)
		protected.GET("/partner/calendar", controllers.RentFlowCarPartnerGetCalendar)
		protected.POST("/partner/availability-blocks", controllers.RentFlowCarPartnerCreateAvailabilityBlock)
		protected.DELETE("/partner/availability-blocks/:blockId", controllers.RentFlowCarPartnerDeleteAvailabilityBlock)
		protected.GET("/partner/promotions", controllers.RentFlowCarPartnerListPromotions)
		protected.POST("/partner/promotions", controllers.RentFlowCarPartnerCreatePromotion)
		protected.PATCH("/partner/promotions/:promotionId", controllers.RentFlowCarPartnerUpdatePromotion)
		protected.DELETE("/partner/promotions/:promotionId", controllers.RentFlowCarPartnerDeletePromotion)
		protected.GET("/partner/addons", controllers.RentFlowCarPartnerListAddons)
		protected.POST("/partner/addons", controllers.RentFlowCarPartnerCreateAddon)
		protected.PATCH("/partner/addons/:addonId", controllers.RentFlowCarPartnerUpdateAddon)
		protected.DELETE("/partner/addons/:addonId", controllers.RentFlowCarPartnerDeleteAddon)
		protected.GET("/partner/leads", controllers.RentFlowCarPartnerListLeads)
		protected.POST("/partner/leads", controllers.RentFlowCarPartnerCreateLead)
		protected.PATCH("/partner/leads/:leadId", controllers.RentFlowCarPartnerUpdateLead)
		protected.DELETE("/partner/leads/:leadId", controllers.RentFlowCarPartnerDeleteLead)
		protected.GET("/partner/members", controllers.RentFlowCarPartnerListMembers)
		protected.POST("/partner/members", controllers.RentFlowCarPartnerCreateMember)
