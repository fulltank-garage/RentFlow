		protected.DELETE("/partner/domains/:domainId", controllers.RentFlowCarPartnerDeleteDomain)
		protected.GET("/partner/support", controllers.RentFlowCarPartnerGetSupport)
		protected.PATCH("/partner/support/tickets/:ticketId", controllers.RentFlowCarPartnerUpdateSupportTicket)
		protected.POST("/partner/support/tickets/:ticketId/messages", controllers.RentFlowCarPartnerCreateSupportMessage)
		protected.GET("/partner/audit-logs", controllers.RentFlowCarPartnerGetAuditLogs)
		protected.GET("/platform/me", controllers.RentFlowCarAdminGetMe)
		protected.GET("/platform/ai/assistant", controllers.RentFlowCarAdminAssistant)
		protected.GET("/platform/overview", controllers.RentFlowCarAdminGetOverview)
		protected.GET("/platform/partners", controllers.RentFlowCarAdminListPartners)
		protected.POST("/platform/partners", controllers.RentFlowCarAdminCreatePartner)
		protected.GET("/platform/domains", controllers.RentFlowCarAdminListDomains)
		protected.GET("/platform/billing", controllers.RentFlowCarAdminGetBilling)
		protected.PATCH("/platform/billing/invoices/:invoiceId", controllers.RentFlowCarAdminUpdateInvoiceStatus)
		protected.GET("/platform/security", controllers.RentFlowCarAdminGetSecurity)
		protected.PATCH("/platform/security/users/:userId", controllers.RentFlowCarAdminUpdateUserSecurity)
		protected.GET("/platform/security/members", controllers.RentFlowCarAdminListPlatformMembers)
		protected.POST("/platform/security/members", controllers.RentFlowCarAdminCreatePlatformMember)
		protected.PATCH("/platform/security/members/:memberId", controllers.RentFlowCarAdminUpdatePlatformMember)
		protected.DELETE("/platform/security/members/:memberId", controllers.RentFlowCarAdminDeletePlatformMember)
		protected.GET("/platform/audit-logs", controllers.RentFlowCarAdminGetAuditLogs)
		protected.GET("/platform/settings", controllers.RentFlowCarAdminGetPlatformSettings)
		protected.PUT("/platform/settings", controllers.RentFlowCarAdminUpdatePlatformSettings)
		protected.PATCH("/platform/settings", controllers.RentFlowCarAdminUpdatePlatformSettings)
		protected.GET("/platform/storefront/page", controllers.RentFlowCarAdminGetStorefrontPage)
		protected.PUT("/platform/storefront/page", controllers.RentFlowCarAdminUpdateStorefrontPage)
		protected.PATCH("/platform/storefront/page", controllers.RentFlowCarAdminUpdateStorefrontPage)
